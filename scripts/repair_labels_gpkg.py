"""
repair_labels_gpkg.py
---------------------
Run this in the QGIS Python Console when a species layer reports one of:

    Cannot reopen datasource ...|layername=<species> in read-only mode
    database is locked
    disk I/O error
    invalid layer / cannot be opened

    exec(open('/path/to/segmentation_model/scripts/repair_labels_gpkg.py').read())

Procedure: back up -> diagnose -> if broken, build a fresh file with
scripts/init_labels_gpkg.py and copy every feature back through the QGIS write
path (so OGR rebuilds the spatial index itself) -> re-bind Geo-SAM.

The old file is NOT deleted: it is renamed to <site>.gpkg.corrupt, and the
backup is kept as <site>.gpkg.bak-<time>.

Common cause
------------
A GeoPackage is SQLite. It tolerates several processes reading/writing on the
SAME filesystem, but NOT two processes seeing the file through two different
mounts (say one on a local disk and one over a network share or FUSE). The two
sides then fight over the WAL `-shm` file, and the result is a corrupted index,
a leftover `.fuse_hidden` file, and a layer that turns read-only.

Avoid it: only ever open `<site>.gpkg` from one machine, through one path. Do
not let Dropbox/Google Drive/OneDrive sync `data/labels/` while you are working.
"""
