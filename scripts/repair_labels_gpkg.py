# GeoPackage geometry blob = 'GP' + version + flags + srs_id(4) + envelope + WKB
_ENV_SIZE = {0: 0, 1: 32, 2: 48, 3: 48, 4: 64}


def _blob_to_wkb(b):
    if not b or bytes(b[0:2]) != b'GP':
        return None
    return bytes(b[8 + _ENV_SIZE.get((b[3] >> 1) & 0x07, 0):])


def _layer_names(path):
    """Every vector layer inside the GeoPackage, read from gpkg_contents."""
    con = sqlite3.connect(path, timeout=5)
    try:
        return [r[0] for r in con.execute(
            "SELECT table_name FROM gpkg_contents WHERE data_type='features'"
            " ORDER BY table_name")]
    finally:
        con.close()


def _is_healthy(path):
    """True when sqlite can read it AND OGR can open every layer."""
    try:
        con = sqlite3.connect(path, timeout=5)
        chk = con.execute('PRAGMA integrity_check').fetchone()[0]
        con.close()
    except Exception as e:
        return False, 'sqlite: %r' % e
    if chk != 'ok':
        return False, 'integrity_check: %s' % chk.splitlines()[0]
    try:
        names = _layer_names(path)
    except Exception as e:
        return False, 'gpkg_contents: %r' % e
    if not names:
        return False, 'no vector layer inside the file'
    total = 0
    for n in names:
        vl = QgsVectorLayer('%s|layername=%s' % (path, n), '_probe', 'ogr')
        if not vl.isValid():
            return False, 'OGR cannot open layer %s' % n
        total += vl.featureCount()
    return True, 'ok (%d layers, %d features)' % (len(names), total)


def repair(repo=REPO, site=SITE, venv_python=VENV_PYTHON, verbose=True):
    say = (lambda m: print(m)) if verbose else (lambda m: None)
    d = os.path.join(repo, 'data/labels', site)
    gpkg = os.path.join(d, site + '.gpkg')
    if not os.path.isfile(gpkg):
        raise RuntimeError('not found: %s' % gpkg)

    # 1. release every QGIS handle
    ids = [lid for lid, l in QgsProject.instance().mapLayers().items()
           if site + '.gpkg' in l.source()]
    for lid in ids:
        l = QgsProject.instance().mapLayer(lid)
        if l is not None and l.isEditable():
            l.rollBack()
    if ids:
        QgsProject.instance().removeMapLayers(ids)
    say('removed %d layer(s) from the project' % len(ids))

    # 2. backup
    bak = os.path.join(d, '%s.gpkg.bak-%s' % (site, time.strftime('%H%M%S')))
    with open(gpkg, 'rb') as fi, open(bak, 'wb') as fo:
        fo.write(fi.read())
    say('backup -> %s' % os.path.basename(bak))

    # 3. diagnose
    healthy, why = _is_healthy(gpkg)
    say('file state: %s (%s)' % ('HEALTHY' if healthy else 'BROKEN', why))
    if healthy:
        say('the file is not corrupted. If it still reports read-only, another '
            'process is holding it: close QGIS, make sure no python/ogr process '
            'is still running, then reopen.')
        return gpkg

    # 4. read the data back out of the backup, layer by layer
    con = sqlite3.connect(bak, timeout=10)
    try:
        names = [r[0] for r in con.execute(
            "SELECT table_name FROM gpkg_contents WHERE data_type='features'"
            " ORDER BY table_name")]
    except Exception:
        names = []
    rescued = {}
    for n in names:
        cols = [r[1] for r in con.execute('PRAGMA table_info("%s")' % n)]
        attrs = [c for c in cols if c not in ('fid', 'geom')]
        if not attrs:
            continue
        rows = con.execute('SELECT geom, %s FROM "%s" ORDER BY fid'
                           % (', '.join('"%s"' % c for c in attrs), n)).fetchall()
        rescued[n] = (attrs, rows)
        say('  rescued %-26s %d row(s)' % (n, len(rows)))
    con.close()
    say('rescued %d layer(s) from the backup' % len(rescued))

    # 5. build a fresh file
    corrupt = gpkg + '.corrupt'
    if os.path.exists(corrupt):
        os.remove(corrupt)
    os.rename(gpkg, corrupt)
    for suffix in ('-wal', '-shm'):
        p = gpkg + suffix
        if os.path.exists(p):
            os.remove(p)
    say('broken file -> %s' % os.path.basename(corrupt))

    p = subprocess.run([venv_python, 'scripts/init_labels_gpkg.py',
                        '--config', 'config.yaml', '--site', site],
                       cwd=repo, capture_output=True, text=True)
    if p.returncode != 0:
        say(p.stdout); say(p.stderr[-2000:])
        raise RuntimeError('failed to create the new file')
    say('created a new file with the correct schema')

    # 6. copy the features back through the QGIS write path
    #    (OGR rebuilds the spatial index itself)
    total = 0
    for n, (attrs, rows) in rescued.items():
        vl = QgsVectorLayer('%s|layername=%s' % (gpkg, n), n, 'ogr')
        if not vl.isValid():
            say('  WARNING: cannot open the new layer %s, skipped' % n)
            continue
        feats, skipped = [], 0
        for r in rows:
            wkb = _blob_to_wkb(r[0])
            if wkb is None:
                skipped += 1
                continue
            g = QgsGeometry()
            g.fromWkb(wkb)
            if g.isEmpty():
                skipped += 1
                continue
            f = QgsFeature(vl.fields())
            f.setGeometry(g)
            for name, val in zip(attrs, r[1:]):
                if val is not None and name in [x.name() for x in vl.fields()]:
                    f[name] = val
            feats.append(f)
        if feats:
            vl.dataProvider().addFeatures(feats)
        vl.reload()
        total += vl.featureCount()
        say('  %-26s %d copied, %d skipped, total %d'
            % (n, len(feats), skipped, vl.featureCount()))
    say('restored %d feature(s) in total' % total)

    healthy, why = _is_healthy(gpkg)
    say('new file: %s (%s)' % ('HEALTHY' if healthy else 'STILL BROKEN', why))
    if not healthy:
        raise RuntimeError('rebuild still broken, keeping %s' % os.path.basename(bak))

    # 7. re-bind Geo-SAM (this also reloads every layer with its colour)
    setup = os.path.join(repo, 'qgis/setup_geosam_session.py')
    if os.path.isfile(setup):
        ns = {}
        exec(open(setup).read(), ns)
        sel = ns.get('selector')
        say('Geo-SAM re-bound: %s' % (sel is not None and hasattr(sel, 'polygon')))

    say('\nDONE. The old files are still at %s and %s; delete them once you have '
        'checked the result.' % (os.path.basename(corrupt), os.path.basename(bak)))
    return gpkg


try:
    repair()
except Exception:
    traceback.print_exc()
