"""
repair_session.py
-----------------
ONE command that puts the QGIS session back into a correct state. Run it in
the Python Console:

    exec(open('/path/to/segmentation_model/scripts/repair_session.py').read())

It does the following, in order:
  1. Remove every temporary thing attached to the session (log collectors,
     hooks, helpers, monkey-patches) - leaving them behind breaks Save.
  2. Reload the plugin to restore the original classes.
  3. Apply the 4 plugin patches and VERIFY them; stop immediately if any
     patch is missing.
  4. Reload the plugin again so the patched code is loaded.
  5. Rebuild the session: load the ortho + the 9 species layers, one colour
     per species, and bind Geo-SAM.
  6. Self-test: binding works on every layer, drawing works, and values land
     in the right columns. Every test polygon is deleted once checked.

Prints a PASS/FAIL table and writes it to <repo>/repair_report.txt.
Leaves nothing behind in the session except a correct state.
"""
import io
import os
import time
import traceback

# ------------------------------------------------------------------- config
# On another machine, do NOT edit this file. Set the 3 variables below ONCE
# per QGIS session, before running any script (see README.md):
#
#   import qgis.utils
#   qgis.utils.BV_REPO   = r'D:\path\to\segmentation_model'
#   qgis.utils.BV_SITE   = 'site_name'
#   qgis.utils.BV_PYTHON = r'C:\...\envs\bunjilview\python.exe'   # optional
#
# If BV_PYTHON is left empty the script reads it from
# data/labels/<site>/site.json.
DEFAULT_REPO = '/Users/huydinh/Desktop/Home/Bunjilview/segmentation_model'
DEFAULT_SITE = 'test1'
DEFAULT_PYTHON = '/opt/homebrew/Caskroom/miniconda/base/envs/bunjilview/bin/python'


def _cfg():
    import json
    import qgis.utils as _qu
    repo = (getattr(_qu, 'BV_REPO', '') or DEFAULT_REPO).rstrip('/\\')
    site = getattr(_qu, 'BV_SITE', '') or DEFAULT_SITE
    py = getattr(_qu, 'BV_PYTHON', '')
    if not py:
        sj = os.path.join(repo, 'data', 'labels', site, 'site.json')
        if os.path.isfile(sj):
            try:
                py = json.load(open(sj)).get('venv_python', '') or ''
            except Exception:
                py = ''
    return repo, site, (py or DEFAULT_PYTHON)


REPO, SITE, VENV_PYTHON = _cfg()
REPORT = os.path.join(REPO, 'repair_report.txt')

_out = io.StringIO()
_res = []


def say(m=''):
    _out.write(str(m) + '\n')


def check(name, ok, detail=''):
    _res.append((name, bool(ok), detail))
    say('%-4s  %-50s %s' % ('PASS' if ok else 'FAIL', name, detail))
    return bool(ok)


def _square(e, dx, size=6.0):
    x0 = e.xMinimum() + 8 + dx
    y0 = e.yMinimum() + 8
    ring = [[x0, y0], [x0 + size, y0], [x0 + size, y0 + size],
            [x0, y0 + size], [x0, y0]]
    return {'type': 'Feature', 'properties': {},
            'geometry': {'type': 'Polygon', 'coordinates': [ring]}}


def main():
    t0 = time.time()
    from qgis.core import QgsApplication, QgsProject
    from qgis.utils import iface
    import qgis.utils

    say('=' * 72)
    say('REPAIR SESSION  -  %s' % time.strftime('%Y-%m-%d %H:%M:%S'))
    say('=' * 72)

    # ---------- 1. remove temporary attachments ----------
    say('\n--- 1. Removing temporary things attached to the session ---')
    removed = 0
    prev = getattr(qgis.utils, '_bv_collector', None)
    if prev is not None:
        try:
            QgsApplication.messageLog().messageReceived.disconnect(prev)
            removed += 1
        except Exception:
            pass
        qgis.utils._bv_collector = None
    hook = getattr(qgis.utils, '_bunjilview_layer_hook', None)
    if hook is not None:
        try:
            iface.layerTreeView().currentLayerChanged.disconnect(hook)
            removed += 1
        except Exception:
            pass
        qgis.utils._bunjilview_layer_hook = None
    for sig, fn in (getattr(qgis.utils, '_bunjilview_raster_hooks', None) or []):
        try:
            sig.disconnect(fn)
            removed += 1
        except Exception:
            pass
    qgis.utils._bunjilview_raster_hooks = None
    for n in ('_bv_chk', '_bv_nxt', '_bv_snap', '_bv_base', '_bv_report',
              '_bv_cleanup', '_bv_instrumented'):
        if hasattr(qgis.utils, n):
            delattr(qgis.utils, n)
            removed += 1
    check('1 cleanup', True, 'removed %d item(s)' % removed)

    # ---------- 2+3+4. reload, patch, reload ----------
    say('\n--- 2. Patching the plugin ---')
    qgis.utils.reloadPlugin('GeoSAM')
    ns = {}
    exec(open(os.path.join(REPO, 'scripts/patch_geosam_fields.py')).read(), ns)
    st = ns['verify']()
    ok = len(st) == 4 and all(v is True for v in st.values())
    check('2 all 4 patches present in the files', ok, repr(st))
    if not ok:
        say('\nSTOPPING: patches incomplete, no point testing further.')
        return
    qgis.utils.reloadPlugin('GeoSAM')

    # ---------- 5. rebuild the session ----------
    say('\n--- 3. Rebuilding the session ---')
    ns2 = {}
    exec(open(os.path.join(REPO, 'qgis/setup_geosam_session.py')).read(), ns2)
    sel = qgis.utils.plugins.get('GeoSAM').wdg_select
    check('3 setup finished, Geo-SAM bound', hasattr(sel, 'polygon'))
    names = ns2['_species_names'](REPO)

    def lay(n):
        return next((l for l in QgsProject.instance().mapLayers().values()
                     if l.name() == n and SITE + '.gpkg' in l.source()), None)

    # ---------- 6. self-test ----------
    say('\n--- 4. Self-test on every layer ---')
    need = ['group_ulid', 'N_GM', 'id', 'Area', 'N_FG', 'N_BG', 'BBox',
            'lb_name', 'lb_note', 'species', 'source', 'score', 'run_ts']
    bad = []
    for n in names:
        l = lay(n)
        if l is None:
            bad.append('%s: could not load' % n)
            continue
        miss = [f for f in need if f not in [x.name() for x in l.fields()]]
        if miss:
            bad.append('%s: missing %r' % (n, miss))
    check('4a all %d layers have the full field set' % len(names), not bad,
          '; '.join(bad)[:120])

    bad = []
    for n in names:
        l = lay(n)
        if l is None:
            continue
        iface.setActiveLayer(l)
        b = sel.polygon.get_layer() if hasattr(sel, 'polygon') else None
        if b is None or b.name() != n:
            bad.append('%s -> %r' % (n, b.name() if b else None))
    check('4b Geo-SAM follows whichever layer you click', not bad,
          '; '.join(bad)[:120])

    # Use the SAME coordinate area for every layer (the ortho extent), and do
    # NOT call reload() before checking: reload() throws away the edit buffer,
    # so if the commit has not landed yet the new feature disappears and the
    # test reports a false failure.
    ras = next((l for l in QgsProject.instance().mapLayers().values()
                if l.name() == SITE), None)
    base_ext = ras.extent() if ras is not None else iface.mapCanvas().extent()
    bad = []
    for i, n in enumerate(names):
        l = lay(n)
        if l is None:
            continue
        iface.setActiveLayer(l)
        before = l.featureCount()
        try:
            sel.polygon.add_geojson_feature_to_layer(
                [_square(base_ext, i * 12.0)], 0, ['fgpt'], max_object_mode=False)
            sel.polygon.commit_changes()
        except Exception as e:
            bad.append('%s: %r' % (n, e))
            continue
        after = l.featureCount()
        if after != before + 1:
            bad.append('%s: %d -> %d' % (n, before, after))
            continue
        f = sorted(l.getFeatures(), key=lambda x: x.id())[-1]
        probs = []
        if not str(f['group_ulid']) or str(f['group_ulid']) == 'NULL':
            probs.append('group_ulid empty')
        if not (30 < (f['Area'] or 0) < 40):
            probs.append('Area=%r' % f['Area'])
        if probs:
            bad.append('%s: %s' % (n, ', '.join(probs)))
        if l.isEditable():
            l.commitChanges()
        l.dataProvider().deleteFeatures([f.id()])
        l.reload()
    check('4c drawing works on every layer, values in the right columns',
          not bad, '; '.join(bad)[:150])

    say('\n--- 5. Polygon count after cleanup ---')
    for n in names:
        l = lay(n)
        if l is not None:
            say('    %-26s %d' % (n, l.featureCount()))

    npass = sum(1 for _, o, _ in _res if o)
    say('\n' + '=' * 72)
    say('RESULT: %d/%d PASS   (%.1fs)' % (npass, len(_res), time.time() - t0))
    for n, o, d in _res:
        if not o:
            say('  FAIL  %s  %s' % (n, d))
    if npass == len(_res):
        say('Ready. Press FG, click on the image, press S. To switch species,')
        say('click that layer in the Layers panel.')
    say('=' * 72)


try:
    main()
except Exception:
    say('\nEXCEPTION:\n' + traceback.format_exc())

open(REPORT, 'w').write(_out.getvalue())
print(_out.getvalue())
