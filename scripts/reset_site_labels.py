"""
reset_site_labels.py
--------------------
WIPE every polygon of a site and start again from 9 empty species layers.

    exec(open('/path/to/segmentation_model/scripts/reset_site_labels.py').read())

Deletes:
  - data/labels/<site>/<site>.gpkg        (every polygon of every species)
  - data/labels/<site>/prototypes/        (so one-vs-rest does not learn from
                                           data you just discarded)

Kept as-is (regenerating these is very slow):
  - _patch_feats.npy, _patch_index.npy, _patch_xy.npy, _tiles.json
  - sam_candidates/
  - site.json

After wiping it recreates the gpkg with 9 empty layers using the correct
schema, then runs repair_session.py to rebuild the session and self-test.

THIS CANNOT BE UNDONE. To avoid running it by accident, CONFIRM must be True
just below.
"""
