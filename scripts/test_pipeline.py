"""
test_pipeline.py
----------------
End-to-end test suite, run it in the QGIS Python Console:

    exec(open('/path/to/segmentation_model/scripts/test_pipeline.py').read())

It exercises the whole workflow:
  A. Patch the plugin + setup, bind to EVERY species layer (all 9)
  B. Draw a polygon into every layer through Geo-SAM's real save path, and
     check the values land in the right columns (no positional shift)
  C. Editing: delete some, add some back
  D. Propagation
  E. Propagate AGAIN on the same layer -> must not duplicate polygons
  F. Delete a few auto polygons and propagate again -> must pick them back up

The test cleans up after itself: every polygon it creates is deleted at the
end, and your data comes back exactly as it was before the run.

The report is written to <repo>/test_report.txt and printed to the console.
"""
