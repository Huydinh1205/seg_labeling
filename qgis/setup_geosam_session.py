"""
setup_geosam_session.py
-----------------------
Run in the QGIS Python Console, once per session and whenever you want to
switch species:

    exec(open('<REPO>/qgis/setup_geosam_session.py').read())
    setup(species='Sphagnum')

What it does:
  1. Loads the orthomosaic and EVERY species layer of the site, each in its
     own colour.
  2. Binds Geo-SAM to the species layer you picked.
  3. Puts that layer into edit mode.
  4. Installs a hook: from then on, just CLICK a layer in the Layers panel and
     Geo-SAM follows it. No need to call setup() again.

ONE LAYER PER SPECIES: the layer name IS the species, so there is no attribute
to fill in when you draw.

The order Geo-SAM requires (getting it wrong fails SILENTLY)
------------------------------------------------------------
1. The layer must carry the FULL Geo-SAM field set (group_ulid, N_GM, id, Area,
   N_FG, N_BG, BBox, lb_name, lb_note). Miss one and you get "The fields of
   this vector do not match the SAM feature fields".
   scripts/init_labels_gpkg.py creates them with the right schema.
2. The IMAGE SOURCE must be set BEFORE the annotation layer.
   set_vector_layer() returns immediately when img_crs_manager does not exist
   yet - no log, no exception.
3. Never set the annotation combo box to None first. Any trip through None
   drags set_vector_layer -> reset_layer(None) -> _init_layer(), which calls
   addAttributes unconditionally and raises "field already exists".
4. scripts/patch_geosam_fields.py must have been run once on this machine.
   Without it Geo-SAM writes attributes BY COLUMN POSITION and your polygon
   vanishes when you press S.
"""
